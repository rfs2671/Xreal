#!/usr/bin/env bash
# g2o 20230806_git, static, Eigen + PCG solvers only (no CHOLMOD/CSparse/OpenGL/apps).
. "$(dirname "$0")/common.sh"
cm "$SRC/g2o" "$BLD/g2o" -DG2O_USE_CHOLMOD=OFF -DG2O_USE_CSPARSE=OFF -DG2O_USE_OPENGL=OFF -DG2O_USE_LOGGING=OFF \
  -DG2O_BUILD_APPS=OFF -DG2O_BUILD_EXAMPLES=OFF -DBUILD_LGPL_SHARED_LIBS=OFF -DG2O_USE_LGPL_LIBS=OFF \
  -DDO_SSE_AUTODETECT=OFF -DG2O_USE_OPENMP=OFF -DBUILD_WITH_MARCH_NATIVE=OFF \
  -DEigen3_DIR="$PREFIX/share/eigen3/cmake"
bi "$BLD/g2o"
