#!/usr/bin/env bash
# rtabmap corelib + utilite as static libraries (no GUI/Qt/app/tools/examples/drivers).
. "$(dirname "$0")/common.sh"
# RTABMAP_NO_OPENCV_STITCHING: libopencv_java4.so exports no stitching symbols (see rtabmap-android-opencv-java4.patch)
OFF=""
for w in QT TORCH PYTHON ONNXRUNTIME PDAL LIBLAS CUDASIFT FREENECT FREENECT2 K4W2 K4A EINSTAR OPENNI OPENNI2 DC1394 \
  GTSAM CERES MRPT CVSBA POINTMATCHER CCCORELIB OPEN3D LOAM FLOAM LIOSAM FLYCAPTURE2 ZED ZEDOC REALSENSE REALSENSE_SLAM \
  REALSENSE2 MYNTEYE DEPTHAI XVSDK ORBBEC_SDK OCTOMAP GRIDMAP CPUTSDF OPENCHISEL ALICE_VISION FOVIS VISO2 DVO ORB_SLAM \
  OKVIS MSCKF_VIO VINS_FUSION OPENVINS CUVSLAM FASTCV OPENMP OPENGV APRILTAG; do OFF="$OFF -DWITH_$w=OFF"; done
cm "$SRC/rtabmap" "$BLD/rtabmap" $OFF \
  -DBUILD_APP=OFF -DBUILD_TOOLS=OFF -DBUILD_EXAMPLES=OFF -DBUILD_TESTING=OFF -DBUILD_PERF_TESTS=OFF -DPCL_OMP=OFF \
  -DWITH_G2O=ON -DWITH_TORO=OFF -DWITH_VERTIGO=ON -DWITH_MADGWICK=ON -DWITH_NANOFLANN=ON -DBUILD_NANOFLANN=ON -DWITH_ORB_OCTREE=ON \
  -DRTABMAP_RES_TOOL="$SCRIPTS/res_tool.bat" \
  -DOpenCV_DIR="$SCRIPTS/opencv_cfg" -DOPENCV_ANDROID="$OPENCV_ANDROID" \
  -DPCL_DIR="$PREFIX/share/pcl-1.15" -DBoost_DIR="$PREFIX/lib/cmake/Boost-1.86.0" -DBoost_USE_STATIC_LIBS=ON \
  -DEigen3_DIR="$PREFIX/share/eigen3/cmake" -Dg2o_DIR="$PREFIX/lib/cmake/g2o" \
  -DSQLite3_INCLUDE_DIR="$PREFIX/include" -DSQLite3_LIBRARY="$PREFIX/lib/libsqlite3.a" \
  -DFLANN_ROOT="$PREFIX" \
  -DCMAKE_CXX_FLAGS="-g0 -DRTABMAP_NO_OPENCV_STITCHING"
bi "$BLD/rtabmap"
